/** @file include/ut0hlc.h
The hybrid logical clock, and the timestamp of Accord: a port of
sql-rust/accord/src/primitives/timestamp.rs and local/time_service.rs. The msb
and lsb encoding is bit for bit that of Rust (unit-tests/test_hlc.cc has
vectors generated by running the Rust code).

A transaction id or number (trx_id_t), on a page and in memory, is a 64 bit
integer, DB_TRX_ID on a clustered record:

  id = (epoch << HLC_EPOCH_SHIFT) | ((hlc - HLC_BASE_US) << HLC_TIME_SHIFT) | node

The integer order of ids is then Accord's: epoch, hlc, node. A Timestamp is
rebuilt from an id alone (id_to_timestamp()) and its encoding is that of Rust. The
widths are here and nowhere else.

  The time   HLC_TIME_BITS, 17.8 years from the base, to about Sep 2044. Fatal past it.
  The node   HLC_NODE_BITS: 64 nodes against the u32 of Rust's NodeId. Config.
  The epoch  HLC_EPOCH_BITS: 512 epochs. It can't wrap: a smaller integer would
             order a new id before old ones, in the views and purge.

An id may be from another node, with a time or an epoch ahead of the local clock.
Treat an id as this tuple. Consecutive ids of a node differ by HLC_ID_STEP or
more, id + 1 would forge an id of another node: id_next() if a next id is needed.
The low bits of the ids of a node are constant, and the top ones nearly: a hash
of an id must mix the time bits (the multiplicative hashes of TrxSys do, the top
bits of the product depend on all of the bits below them; test_hlc.cc tests it).

Id 0 is "no id". The time of the clock is at least 1, so no id is ever 0, even
for node 0 in epoch 0, with a wall clock before the base.

THE CLOCK (TimeService)

The algorithm is TimeService of Rust, in its units: the wall clock is microseconds
since the UNIX epoch, next = max(wall, last + 1), update() raises last, at_least()
is update() then next. The state differs: Rust has two atomics, an epoch and
last_hlc, and it reads the epoch after the compare and swap, so a racing set_epoch
could give a later hlc the older epoch. Here epoch and time are one atomic word,
the id of node 0 of the clock's last value: they advance together, and the words
the clock goes through, so the ids of this node, strictly increase as integers,
also across set_epoch(). Unlike Rust set_epoch() can't lower the epoch, and
a value past the range of the time (Rust has 64 bits for it) isn't taken by update().
*/

#pragma once

#include "ut0logger.h"

#include <atomic>
#include <compare>
#include <cstdint>
#include <ctime>
#include <format>

namespace ut {

/** 2026-11-01T00:00:00Z in microseconds since the UNIX epoch: the clock doesn't
store time before it. */
constexpr uint64_t HLC_BASE_US = 1793491200000000ULL;

/** The layout of an id, low bits first: the only place of these widths. */
constexpr uint32_t HLC_NODE_BITS = 6;
constexpr uint32_t HLC_TIME_BITS = 49;
constexpr uint32_t HLC_EPOCH_BITS = 9;

static_assert(HLC_NODE_BITS + HLC_TIME_BITS + HLC_EPOCH_BITS == 64);

constexpr uint32_t HLC_TIME_SHIFT = HLC_NODE_BITS;
constexpr uint32_t HLC_EPOCH_SHIFT = HLC_NODE_BITS + HLC_TIME_BITS;

/** The first node id and the first epoch that can't be in an id. */
constexpr uint32_t HLC_MAX_NODES = uint32_t(1) << HLC_NODE_BITS;
constexpr uint32_t HLC_MAX_EPOCHS = uint32_t(1) << HLC_EPOCH_BITS;

constexpr uint64_t HLC_NODE_MASK = (uint64_t(1) << HLC_NODE_BITS) - 1;
constexpr uint64_t HLC_TIME_MASK = (uint64_t(1) << HLC_TIME_BITS) - 1;

/** The difference of two consecutive ids of a node. */
constexpr uint64_t HLC_ID_STEP = uint64_t(1) << HLC_TIME_SHIFT;

/** The time of the last value that can be an id: one less than the bits hold,
so that the high water mark above it (id limit) doesn't spill into the epoch. */
constexpr uint64_t HLC_MAX_TIME = HLC_TIME_MASK - 1;

/** Flags of a Timestamp, the low 4 bits of its lsb. */
constexpr uint8_t TS_REJECTED = 1;
constexpr uint8_t TS_UNSTABLE = 2;
constexpr uint8_t TS_HLC_BOUND = 4;
constexpr uint8_t TS_SHARD_BOUND = 8;

/** An Accord timestamp: 48 bits of epoch, 64 bits of hybrid logical clock, 4 of
flags, the node. Ordered by msb, lsb without flags, node; flags are ignored. */
class Timestamp {
 public:
  constexpr Timestamp() noexcept = default;

  constexpr Timestamp(uint64_t epoch, uint64_t hlc, uint32_t node, uint8_t flags = 0) noexcept
      : m_msb((epoch << 16) | (hlc >> 60)), m_lsb(((hlc & ((uint64_t(1) << 60) - 1)) << 4) | (uint64_t(flags) & FLAG_MASK)), m_node(node) {}

  [[nodiscard]] static constexpr Timestamp from_bits(uint64_t msb, uint64_t lsb, uint32_t node) noexcept {
    Timestamp ts;

    ts.m_msb = msb;
    ts.m_lsb = lsb;
    ts.m_node = node;

    return ts;
  }

  [[nodiscard]] static constexpr Timestamp zero() noexcept { return Timestamp{}; }

  [[nodiscard]] static constexpr Timestamp max() noexcept { return from_bits(UINT64_MAX, ~FLAG_MASK, UINT32_MAX); }

  [[nodiscard]] constexpr uint64_t msb() const noexcept { return m_msb; }
  [[nodiscard]] constexpr uint64_t lsb() const noexcept { return m_lsb; }
  [[nodiscard]] constexpr uint32_t node() const noexcept { return m_node; }
  [[nodiscard]] constexpr uint64_t epoch() const noexcept { return m_msb >> 16; }
  [[nodiscard]] constexpr uint8_t flags() const noexcept { return uint8_t(m_lsb & FLAG_MASK); }

  /** The shift drops all but the low 4 of the bits above the 60: as in Rust. */
  [[nodiscard]] constexpr uint64_t hlc() const noexcept { return ((m_msb & 0xFFFF) << 60) | (m_lsb >> 4); }

  [[nodiscard]] constexpr bool is_rejected() const noexcept { return (m_lsb & TS_REJECTED) != 0; }
  [[nodiscard]] constexpr bool is_unstable() const noexcept { return (m_lsb & TS_UNSTABLE) != 0; }
  [[nodiscard]] constexpr bool is_hlc_bound() const noexcept { return (m_lsb & TS_HLC_BOUND) != 0; }
  [[nodiscard]] constexpr bool is_shard_bound() const noexcept { return (m_lsb & TS_SHARD_BOUND) != 0; }

  [[nodiscard]] constexpr Timestamp with_added_flags(uint8_t flags) const noexcept {
    return from_bits(m_msb, m_lsb | (uint64_t(flags) & FLAG_MASK), m_node);
  }

  [[nodiscard]] constexpr Timestamp without_flags() const noexcept { return from_bits(m_msb, m_lsb & ~FLAG_MASK, m_node); }

  [[nodiscard]] constexpr Timestamp with_node(uint32_t node) const noexcept { return from_bits(m_msb, m_lsb, node); }

  [[nodiscard]] constexpr Timestamp with_epoch(uint64_t epoch) const noexcept { return Timestamp(epoch, hlc(), m_node, flags()); }

  [[nodiscard]] constexpr std::strong_ordering operator<=>(const Timestamp &rhs) const noexcept {
    if (auto c = m_msb <=> rhs.m_msb; c != 0) {
      return c;
    } else if (auto d = (m_lsb & ~FLAG_MASK) <=> (rhs.m_lsb & ~FLAG_MASK); d != 0) {
      return d;
    } else {
      return m_node <=> rhs.m_node;
    }
  }

  /** Equal in the ordering: flags are ignored (Rust's == compares them, its cmp doesn't). */
  [[nodiscard]] constexpr bool operator==(const Timestamp &rhs) const noexcept { return (*this <=> rhs) == 0; }

  /** Both flags merged, the greater timestamp. */
  [[nodiscard]] constexpr Timestamp merge_max(const Timestamp &rhs) const noexcept {
    return *this < rhs ? rhs.with_added_flags(flags()) : with_added_flags(rhs.flags());
  }

  /** Both flags merged, the lesser timestamp. */
  [[nodiscard]] constexpr Timestamp merge_min(const Timestamp &rhs) const noexcept {
    return *this < rhs ? with_added_flags(rhs.flags()) : rhs.with_added_flags(flags());
  }

 private:
  static constexpr uint64_t FLAG_MASK = 0xF;

  uint64_t m_msb{};
  uint64_t m_lsb{};
  uint32_t m_node{};
};

/** @return true if the clock value hlc can be in an id: past the base (no id
is 0), and within the bits. */
[[nodiscard]] constexpr bool hlc_fits(uint64_t hlc) noexcept { return hlc > HLC_BASE_US && hlc - HLC_BASE_US <= HLC_MAX_TIME; }

/** @return the id of an epoch, a clock value and a node; all must fit. */
[[nodiscard]] constexpr uint64_t id_pack(uint64_t epoch, uint64_t hlc, uint32_t node) noexcept {
  return (epoch << HLC_EPOCH_SHIFT) | ((hlc - HLC_BASE_US) << HLC_TIME_SHIFT) | (uint64_t(node) & HLC_NODE_MASK);
}

[[nodiscard]] constexpr uint64_t id_to_epoch(uint64_t id) noexcept { return id >> HLC_EPOCH_SHIFT; }

/** @return the clock value of an id, UNIX microseconds. */
[[nodiscard]] constexpr uint64_t id_to_hlc(uint64_t id) noexcept { return ((id >> HLC_TIME_SHIFT) & HLC_TIME_MASK) + HLC_BASE_US; }

[[nodiscard]] constexpr uint32_t id_to_node(uint64_t id) noexcept { return uint32_t(id & HLC_NODE_MASK); }

/** @return the full timestamp of an id. */
[[nodiscard]] constexpr Timestamp id_to_timestamp(uint64_t id) noexcept { return Timestamp(id_to_epoch(id), id_to_hlc(id), id_to_node(id)); }

/** @return the id of a timestamp, false if it can't be one: before the base, or a
part doesn't fit. Flags are not in an id. */
[[nodiscard]] constexpr bool id_of_timestamp(const Timestamp &ts, uint64_t &id) noexcept {
  if (!hlc_fits(ts.hlc()) || ts.node() >= HLC_MAX_NODES || ts.epoch() >= HLC_MAX_EPOCHS) {
    return false;
  }

  id = id_pack(ts.epoch(), ts.hlc(), ts.node());

  return true;
}

/** @return the next and the previous id of the same epoch and node, in time. */
[[nodiscard]] constexpr uint64_t id_next(uint64_t id) noexcept { return id + HLC_ID_STEP; }
[[nodiscard]] constexpr uint64_t id_prev(uint64_t id) noexcept { return id - HLC_ID_STEP; }

/** @return the smallest id, of any node, above every id of a clock word or below:
the high water mark of a read view at the word. */
[[nodiscard]] constexpr uint64_t word_id_limit(uint64_t word) noexcept { return word + HLC_ID_STEP; }

/** The clock. See THE CLOCK at the top of this file. All of the word's operations
are sequentially consistent, not the acquire and release of Rust: the proofs of
trx0sys.h and ut0lflist.h use the total order (the same instructions on x86-64). */
class TimeService {
 public:
  TimeService(uint32_t node, uint64_t epoch) noexcept : m_node(node), m_word(id_pack(epoch, HLC_BASE_US + 1, 0)) {}

  TimeService(const TimeService &) = delete;
  TimeService &operator=(const TimeService &) = delete;

  [[nodiscard]] uint64_t epoch() const noexcept { return id_to_epoch(read_word()); }

  /** Raise the epoch, with the time unchanged. Fatal past the last epoch: a wrap
  would order later ids before earlier ones. Lower is ignored, for the same reason. */
  void set_epoch(uint64_t epoch) noexcept {
    if (epoch >= HLC_MAX_EPOCHS) [[unlikely]] {
      log_fatal(std::format("Epoch {} doesn't fit in a transaction id, the last is {}", epoch, HLC_MAX_EPOCHS - 1));
    }

    auto word = read_word();

    while (id_to_epoch(word) < epoch) {
      const auto next = (word & ~(~uint64_t(0) << HLC_EPOCH_SHIFT)) | (epoch << HLC_EPOCH_SHIFT);

      if (m_word.compare_exchange_weak(word, next, std::memory_order_seq_cst, std::memory_order_seq_cst)) {
        return;
      }
    }
  }

  [[nodiscard]] uint32_t node() const noexcept { return m_node.load(std::memory_order_relaxed); }

  /** Only before the clock is in use (TrxSys::start()). */
  void set_node(uint32_t node) noexcept { m_node.store(node, std::memory_order_relaxed); }

  /** @return microseconds since the UNIX epoch. A vDSO call, no syscall. */
  [[nodiscard]] uint64_t wall() const noexcept {
    if (const auto w = m_wall_override.load(std::memory_order_relaxed); w != 0) [[unlikely]] {
      return w;
    }

    timespec ts;

    (void)clock_gettime(CLOCK_REALTIME, &ts);

    return uint64_t(ts.tv_sec) * 1000000 + uint64_t(ts.tv_nsec) / 1000;
  }

  /** @return the word: the id of node 0 at the last value issued or received. */
  [[nodiscard]] uint64_t read_word() const noexcept { return m_word.load(std::memory_order_seq_cst); }

  /** @return the last value issued or received, UNIX microseconds. */
  [[nodiscard]] uint64_t read() const noexcept { return id_to_hlc(read_word()); }

  /**
   * Issues a new value, greater than all before it and than the wall clock.
   *
   * @param[in] wall_us  The wall clock, it may be old.
   *
   * @return the word of the new value.
   */
  [[nodiscard]] uint64_t next_word(uint64_t wall_us) noexcept {
    /* The time of the wall clock in the position of the word. A bad clock, before
    the base, gives 0: no underflow, the word still goes by last + 1. */
    const uint64_t wall_time = wall_us > HLC_BASE_US ? (wall_us - HLC_BASE_US) << HLC_TIME_SHIFT : 0;

    auto word = m_word.load(std::memory_order_seq_cst);

    for (;;) {
      const auto high = word & (~uint64_t(0) << HLC_EPOCH_SHIFT);
      const auto low = word ^ high;
      const auto time = low + HLC_ID_STEP > wall_time ? low + HLC_ID_STEP : wall_time;

      if ((time >> HLC_TIME_SHIFT) > HLC_MAX_TIME) [[unlikely]] {
        log_fatal(std::format("The clock ran out of the {} bits of time of a transaction id", HLC_TIME_BITS));
      }

      const auto next = high | time;

      if (m_word.compare_exchange_weak(word, next, std::memory_order_seq_cst, std::memory_order_seq_cst)) {
        return next;
      }
    }
  }

  [[nodiscard]] uint64_t next_hlc(uint64_t wall_us) noexcept { return id_to_hlc(next_word(wall_us)); }

  [[nodiscard]] uint64_t next_hlc() noexcept { return next_hlc(wall()); }

  /** The epoch comes with the value, from the one word (Rust reads it later). */
  [[nodiscard]] Timestamp next_timestamp() noexcept {
    const auto word = next_word(wall());

    return Timestamp(id_to_epoch(word), id_to_hlc(word), node());
  }

  /** Raise the clock to the hlc of received, if it is ahead. The epoch of received
  doesn't count: as in Rust. */
  void update(const Timestamp &received) noexcept { update_hlc(received.hlc()); }

  /** A value below the base is below the clock; one past the range of the time
  is not taken, rather than stopping the clock (TrxSys::clock_update() refuses it). */
  void update_hlc(uint64_t hlc) noexcept {
    if (!hlc_fits(hlc)) {
      return;
    }

    const auto time = (hlc - HLC_BASE_US) << HLC_TIME_SHIFT;

    auto word = read_word();

    for (;;) {
      const auto high = word & (~uint64_t(0) << HLC_EPOCH_SHIFT);

      if ((word ^ high) >= time || m_word.compare_exchange_weak(word, high | time, std::memory_order_seq_cst, std::memory_order_seq_cst)) {
        return;
      }
    }
  }

  /** @return a new timestamp greater than min, if they are of one epoch. */
  [[nodiscard]] Timestamp at_least(const Timestamp &min) noexcept {
    update(min);

    return next_timestamp();
  }

  /** Set the clock, up or down: startup. */
  void reset(uint64_t epoch, uint64_t hlc) noexcept { m_word.store(id_pack(epoch, hlc, 0), std::memory_order_seq_cst); }

  /** Set the word to any value: tests. */
  void reset_word(uint64_t word) noexcept { m_word.store(word, std::memory_order_seq_cst); }

  /** For tests: the wall clock reads w_us from now on; 0 for the real one. */
  void set_wall(uint64_t w_us) noexcept { m_wall_override.store(w_us, std::memory_order_relaxed); }

 private:
  std::atomic<uint32_t> m_node;
  std::atomic<uint64_t> m_wall_override{};

  /** Alone on its cache line: every begin and commit writes it. */
  alignas(64) std::atomic<uint64_t> m_word;
  char m_pad[64 - sizeof(std::atomic<uint64_t>)]{};
};

}  // namespace ut
